-- One row per website/page. Admin writes are protected by private.is_admin().

create table if not exists public.theme_page_settings (
  theme_page_id bigint generated by default as identity primary key,
  website_key text not null,
  page_key text not null,
  page_name text not null,
  is_active boolean not null default true,
  mode text not null default 'light' check (mode in ('light','dark','system')),
  background_color text not null default '#fff8f5',
  surface_color text not null default '#fffaf7',
  surface_elevated_color text not null default '#ffffff',
  section_color text not null default '#fff1ec',
  header_color text not null default '#ffffff',
  footer_color text not null default '#3a0808',
  text_color text not null default '#241716',
  muted_text_color text not null default '#756a67',
  heading_color text not null default '#c92b26',
  primary_color text not null default '#d92d27',
  primary_dark_color text not null default '#a91f1b',
  secondary_color text not null default '#7b4cc7',
  accent_color text not null default '#e7ad21',
  link_color text not null default '#b72b26',
  button_background_color text not null default '#d92d27',
  button_text_color text not null default '#ffffff',
  border_color text not null default '#ead8d1',
  border_strong_color text not null default '#d9bcb3',
  input_background_color text not null default '#ffffff',
  input_border_color text not null default '#decac3',
  card_shadow_color text not null default 'rgba(80,20,15,.10)',
  hero_background_color text not null default '#fff2dc',
  banner_background_color text not null default '#fff0e9',
  nav_background_color text not null default '#ffffff',
  nav_text_color text not null default '#241716',
  font_heading text not null default 'system-ui',
  font_body text not null default 'system-ui',
  radius_small text not null default '10px',
  radius_medium text not null default '16px',
  radius_large text not null default '24px',
  component_tokens jsonb not null default '{}'::jsonb,
  custom_css jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (website_key,page_key)
);

create index if not exists idx_theme_page_settings_website on public.theme_page_settings(website_key,is_active);
alter table public.theme_page_settings enable row level security;
revoke all on public.theme_page_settings from anon, authenticated;
grant select on public.theme_page_settings to anon, authenticated;
grant select,insert,update,delete on public.theme_page_settings to authenticated;
drop policy if exists theme_public_read on public.theme_page_settings;
create policy theme_public_read on public.theme_page_settings for select to anon,authenticated using (is_active=true);
drop policy if exists theme_admin_write on public.theme_page_settings;
create policy theme_admin_write on public.theme_page_settings for all to authenticated using (private.is_admin()) with check (private.is_admin());

