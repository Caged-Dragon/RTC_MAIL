-- Component-level editor: lets Admin target an exact path such as
-- Main / Portfolio -> Home -> About Us -> Heading.
create table if not exists public.theme_component_settings (
  theme_component_id bigint generated by default as identity primary key,
  website_key text not null,
  page_key text not null,
  section_key text not null,
  section_name text not null,
  component_key text not null,
  component_name text not null,
  component_type text not null default 'component',
  font_family text,
  font_size text,
  font_weight text,
  line_height text,
  letter_spacing text,
  text_color text,
  background_color text,
  border_color text,
  border_width text,
  border_radius text,
  box_shadow text,
  padding text,
  margin text,
  width text,
  max_width text,
  text_align text,
  component_tokens jsonb not null default '{}'::jsonb,
  content_value text,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (website_key,page_key,section_key,component_key)
);
create index if not exists idx_theme_component_lookup on public.theme_component_settings(website_key,page_key,section_key,is_active,sort_order);
alter table public.theme_component_settings enable row level security;
revoke all on public.theme_component_settings from anon,authenticated;
grant select on public.theme_component_settings to anon,authenticated;
grant select,insert,update,delete on public.theme_component_settings to authenticated;
drop policy if exists theme_component_public_read on public.theme_component_settings;
create policy theme_component_public_read on public.theme_component_settings for select to anon,authenticated using (is_active=true);
drop policy if exists theme_component_admin_write on public.theme_component_settings;
create policy theme_component_admin_write on public.theme_component_settings for all to authenticated using (private.is_admin()) with check (private.is_admin());
create or replace function public.set_theme_component_updated_at() returns trigger language plpgsql set search_path=public as $$ begin new.updated_at=now(); return new; end $$;
drop trigger if exists trg_theme_component_updated_at on public.theme_component_settings;
create trigger trg_theme_component_updated_at before update on public.theme_component_settings for each row execute function public.set_theme_component_updated_at();
